#!/usr/bin/env python3
"""Generate the host census's lists of the volume's owners from the kernel's.

src/include/ground_owner.h holds the one list of GroundOwners — every owner of
a block of a volume's ground, its name, whether it owns alone, and the formats
it owns ground in — and the mount's GroundCensus asks exactly those of the
volume's format. tools/volume-read.py's censuses must ask the same owners of
the same image, or the two name different blocks; so its lists are not
written a second time by hand, they are written out of the header by this,
into tools/volumeread/ground_owners.py: GROUND_OWNERS, the owners of format
v1's census (census.py), and BOOK_OWNERS, of format v2's (bookcensus.py).

    tools/gen_ground_owners.py            write the list
    tools/gen_ground_owners.py --check    exit 1 when the written list is stale
"""

import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HEADER = os.path.join(ROOT, "src", "include", "ground_owner.h")
OUT = os.path.join(ROOT, "tools", "volumeread", "ground_owners.py")

LINE = re.compile(r'X\(\s*(GROUND_[A-Z_]+)\s*,\s*"([a-z_]+)"\s*,\s*([01])\s*,\s*([123])\s*\)')
FORMAT_V1, FORMAT_V2 = 1, 2


def Owners():
    with open(HEADER) as f:
        owners = LINE.findall(f.read())
    if not owners:
        sys.exit("gen_ground_owners: no X(...) owner lines in %s" % HEADER)
    return owners


def Listed(name, owners, fmt):
    """The lines of one format's list: (name, owns alone) in the header's order."""
    lines = ["%s = (" % name]
    lines += ['    ("%s", %s),   # %s' % (who, "True" if alone == "1" else "False", ident)
              for ident, who, alone, formats in owners if int(formats) & fmt]
    return lines + [")", ""]


def Text(owners):
    lines = ['"""The owners of a volume\'s ground, as src/include/ground_owner.h lists them.',
             "",
             "GENERATED by tools/gen_ground_owners.py from that header — not to be",
             'edited by hand: run the generator, and the censuses follow the kernel."""',
             "",
             "# Format v1's census (census.py), then format v2's (bookcensus.py)."]
    lines += Listed("GROUND_OWNERS", owners, FORMAT_V1)
    lines += Listed("BOOK_OWNERS", owners, FORMAT_V2)
    lines += ["GROUND_OWNER_ALONE = dict(GROUND_OWNERS)",
              "BOOK_OWNER_ALONE = dict(BOOK_OWNERS)",
              ""]
    return "\n".join(lines)


def main():
    text = Text(Owners())
    if sys.argv[1:] == ["--check"]:
        have = open(OUT).read() if os.path.exists(OUT) else ""
        if have != text:
            sys.exit("gen_ground_owners: %s is stale — run tools/gen_ground_owners.py" % OUT)
        return
    with open(OUT, "w") as f:
        f.write(text)
    print("gen_ground_owners: %s" % OUT)


if __name__ == "__main__":
    main()
