#!/usr/bin/env python3
"""gen_color_light.py — src/include/boxos_color_light.h, the light an sRGB
number shows and the number nearest a light, written out of sRGB's own curve
(IEC 61966-2-1).

    python3 tools/gen_color_light.py > src/include/boxos_color_light.h

Not a build dependency: the header is checked in, and the curve is a standard
that does not change. The scene stand (tools/scene_stand.c) works both tables
out again from the curve and holds the header to them, so a table edited by
hand, or written by another curve, fails the gates.

Light runs 0 to 65535. A number's light is the curve's, rounded, halves up;
the number of a light is read in 4096 steps, each the number nearest the
light in the middle of its step.
"""
import math

LIGHT_MOST = 65535
STEPS = 4096


def nearest(x):
    """x to the nearest whole, halves up — as the stand rounds, so both agree."""
    return int(math.floor(x + 0.5))


def light_of(code):
    value = code / 255.0
    linear = value / 12.92 if value <= 0.04045 else ((value + 0.055) / 1.055) ** 2.4
    return nearest(linear * LIGHT_MOST)


def code_of(step):
    light = (step + 0.5) / STEPS
    value = light * 12.92 if light <= 0.0031308 else 1.055 * light ** (1 / 2.4) - 0.055
    return nearest(min(max(value, 0.0), 1.0) * 255.0)


def rows(values, per_row, width):
    return ["    " + " ".join("%*d," % (width, v) for v in values[i:i + per_row])
            for i in range(0, len(values), per_row)]


def main():
    lights = [light_of(c) for c in range(256)]
    codes = [code_of(s) for s in range(STEPS)]
    assert lights[0] == 0 and lights[255] == LIGHT_MOST and codes[0] == 0 and codes[-1] == 255
    assert all(a < b for a, b in zip(lights, lights[1:]))
    assert all(a <= b for a, b in zip(codes, codes[1:]))

    out = [
        "/*",
        " * boxos_color_light.h — the light an sRGB number shows, and the number",
        " * nearest a light: sRGB's own curve (IEC 61966-2-1), the one way colours",
        " * are mixed where one is laid over another (boxos_color.h, BoxColorOver).",
        " * GENERATED by tools/gen_color_light.py; not edited by hand.",
        " *",
        " * Light runs 0 to %d. BoxColorLightOf[n] is the light of the number n," % LIGHT_MOST,
        " * rounded, halves up; BoxColorCodeOf[s] the number nearest the light in the",
        " * middle of step s of %d, so a light L is written back as" % STEPS,
        " * BoxColorCodeOf[L >> 4].",
        " *",
        " * The includer supplies uint8_t and uint16_t.",
        " */",
        "#ifndef BOXOS_COLOR_LIGHT_H",
        "#define BOXOS_COLOR_LIGHT_H",
        "",
        "#define BOX_COLOR_LIGHT_MOST %du" % LIGHT_MOST,
        "",
        "static const uint16_t BoxColorLightOf[256] = {",
        *rows(lights, 8, 5),
        "};",
        "",
        "static const uint8_t BoxColorCodeOf[%d] = {" % STEPS,
        *rows(codes, 16, 3),
        "};",
        "",
        "#endif /* BOXOS_COLOR_LIGHT_H */",
    ]
    print("\n".join(out))


if __name__ == "__main__":
    main()
